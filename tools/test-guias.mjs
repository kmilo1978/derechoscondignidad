import { spawn } from 'node:child_process';
import fs from 'node:fs';
const ch = spawn('C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', ['--headless=new', '--disable-gpu', '--remote-debugging-port=9555', '--window-size=1440,900', '--user-data-dir=' + process.env.TEMP + '\\chr10', 'about:blank'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 3000));
const tabs = await (await fetch('http://127.0.0.1:9555/json')).json();
const ws = new WebSocket(tabs.find((t) => t.type === 'page').webSocketDebuggerUrl);
await new Promise((r) => (ws.onopen = r));
let id = 0; const pend = {};
const send = (method, params = {}) => new Promise((r) => { const i = ++id; pend[i] = r; ws.send(JSON.stringify({ id: i, method, params })); });
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pend[m.id]) pend[m.id](m.result); if (m.method === 'Runtime.exceptionThrown') console.log('ERROR JS', JSON.stringify(m.params).slice(0, 300)); };
await send('Runtime.enable'); await send('Page.enable');
await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false });
await send('Page.navigate', { url: 'http://localhost:5174/blog/' });
await new Promise((r) => setTimeout(r, 2500));
const ev = async (e) => (await send('Runtime.evaluate', { expression: e, returnByValue: true })).result.value;
console.log('guías visibles al inicio:', await ev("document.querySelector('[data-guide-count]').textContent"));
await ev("[...document.querySelectorAll('[data-guide-filter]')].find(b=>b.dataset.guideFilter==='SOAT').click()");
console.log('filtro SOAT:', await ev("document.querySelector('[data-guide-count]').textContent"));
await ev("(()=>{const i=document.querySelector('[data-guide-search]');i.value='aseguradora';i.dispatchEvent(new Event('input'))})()");
console.log('SOAT + búsqueda "aseguradora":', await ev("document.querySelector('[data-guide-count]').textContent"));
await ev("[...document.querySelectorAll('[data-guide-filter]')].find(b=>b.dataset.guideFilter==='all').click()");
console.log('Todas + "aseguradora":', await ev("document.querySelector('[data-guide-count]').textContent"));
console.log('alto del header (px, una línea ≈ 80):', await ev("document.querySelector('header').offsetHeight"));
console.log('minutos de lectura (primeras 3):', await ev("[...document.querySelectorAll('[data-guides] a')].slice(0,3).map(a=>a.textContent.match(/(\\d+) min/)?.[1]).join(', ')"));
const shot = await send('Page.captureScreenshot', { format: 'png', clip: { x: 0, y: 0, width: 1440, height: 260, scale: 1 } });
fs.writeFileSync('../sitio/menu.png', Buffer.from(shot.data, 'base64'));
ch.kill(); process.exit(0);
