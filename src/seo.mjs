export function areaFaqs(slug, area) {
  const seo = AREA_SEO[slug];
  const shortLower = area.short.charAt(0).toLowerCase() + area.short.slice(1);
  const faqs = [];
  if (seo?.answer) {
    faqs.push([`¿Cómo actúa Derechos con Dignidad en ${shortLower}?`, seo.answer]);
  }
  if (area.listTitle && area.listItems?.length) {
    faqs.push([
      area.listTitle.endsWith('?') ? area.listTitle : `${area.listTitle}`,
      area.listItems.join('; ') + '.',
    ]);
  }
  if (area.services?.length) {
    faqs.push([
      area.servicesTitle.endsWith('?') ? area.servicesTitle : `¿Qué acciones jurídicas incluye ${shortLower}?`,
      area.services.map(([t, d]) => `${t}: ${d}`).join(' '),
    ]);
  }
  faqs.push([
    '¿La consulta inicial tiene costo o compromete la confidencialidad?',
    'La primera orientación jurídica es gratuita y se maneja bajo estricta confidencialidad y reserva profesional, con disponibilidad 24/7 desde Medellín para todo el país.',
  ]);
  return faqs;
}

